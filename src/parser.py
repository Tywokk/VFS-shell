"""Разбор строки ввода на команду и аргументы."""


def parse(line):
    """Разделить строку по пробелам на команду и список аргументов.

    Пустая строка (или только пробелы) даёт пустую команду.

    Args:
        line: введённая пользователем строка.

    Returns:
        Кортеж (команда, список аргументов).
    """
    parts = line.split()
    if not parts:
        return "", []
    return parts[0], parts[1:]
